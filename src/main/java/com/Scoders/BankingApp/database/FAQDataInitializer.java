    public static void clearAllFAQs() {
        try {
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:sqlite:bank.db");
            java.sql.Statement stmt = conn.createStatement();
            stmt.executeUpdate("DELETE FROM FAQ");
            conn.close();
            System.out.println("All FAQs cleared.");
        } catch (java.sql.SQLException e) {
            System.out.println("Error clearing FAQs: " + e.getMessage());
        }
    }
